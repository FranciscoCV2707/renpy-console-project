#include "font.h"

#define FRAMEBUFFER_WIDTH 256
#define GLYPH_COLUMNS     5
#define GLYPH_ROWS        8
#define GLYPH_ADVANCE     6

struct font_glyph {
	char code;
	u8 rows[GLYPH_ROWS];
};

static const struct font_glyph glyphs[] = {
    {'H', {0x88, 0x88, 0x88, 0xF8, 0x88, 0x88, 0x88, 0x00}}, {'G', {0x70, 0x88, 0x80, 0xB8, 0x88, 0x88, 0x70, 0x00}},
    {'S', {0x78, 0x80, 0x80, 0x70, 0x10, 0x10, 0xF0, 0x00}}, {'a', {0x00, 0x00, 0x70, 0x10, 0x78, 0x88, 0x78, 0x00}},
    {'d', {0x10, 0x10, 0x78, 0x88, 0x88, 0x88, 0x78, 0x00}}, {'e', {0x00, 0x00, 0x70, 0x88, 0xF8, 0x80, 0x70, 0x00}},
    {'l', {0xC0, 0x40, 0x40, 0x40, 0x40, 0x40, 0x40, 0x00}}, {'m', {0x00, 0x00, 0xF8, 0xA8, 0xA8, 0xA8, 0xA8, 0x00}},
    {'n', {0x00, 0x00, 0xF8, 0x88, 0x88, 0x88, 0x88, 0x00}}, {'o', {0x00, 0x00, 0x70, 0x88, 0x88, 0x88, 0x70, 0x00}},
    {'s', {0x00, 0x00, 0x78, 0x80, 0x70, 0x10, 0xF0, 0x00}}, {'t', {0x00, 0x20, 0x70, 0x20, 0x20, 0x20, 0x10, 0x00}},
};

static const u8 *glyph_rows(char code)
{
	for (unsigned int i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++) {
		if (glyphs[i].code == code) {
			return glyphs[i].rows;
		}
	}
	return 0;
}

void font_draw_text(u16 *framebuffer, int x, int y, const char *text, u16 color)
{
	for (int i = 0; text[i] != '\0'; i++) {
		const u8 *rows = glyph_rows(text[i]);
		if (rows != 0) {
			for (int row = 0; row < GLYPH_ROWS; row++) {
				for (int column = 0; column < GLYPH_COLUMNS; column++) {
					if (rows[row] & (0x80 >> column)) {
						framebuffer[(y + row) * FRAMEBUFFER_WIDTH + x + i * GLYPH_ADVANCE +
						            column] = color;
					}
				}
			}
		}
	}
}
